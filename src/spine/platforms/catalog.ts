/**
 * Platform inbound classes (TR-PLATFORMS-2026-10-19).
 *
 * Six field-service and money platforms are named peers of the servicetitan and
 * probooks inbound classes. Each one has its own FragGate sourceKind, its own
 * local drop folder (data/inbound/<kind>/), its own mapper into the runtime's
 * normalized trade entities, an optional read-only live pull that only calls the
 * vendor's documented public API, and its own write-back permission that runs
 * only through the approval gate (src/approvals/).
 *
 * Nothing here has been tested against a live tenant. Live pull is optional,
 * read-only, off until the operator names env vars in a local config, and every
 * pulled document is still admitted as MEDIUM, UNVERIFIED.
 */

export const PLATFORM_KINDS = ["jobber", "housecallpro", "square", "quickbooks", "fieldedge", "servicefusion"] as const;
export type PlatformKind = (typeof PLATFORM_KINDS)[number];

/** Normalized entities a platform can carry. Same names as the trades-app class plus payment and estimate. */
export const PLATFORM_ENTITIES = [
  "job",
  "appointment",
  "customer",
  "invoice",
  "payment",
  "estimate",
  "technician",
  "pricebook",
  "equipment"
] as const;
export type PlatformEntity = (typeof PLATFORM_ENTITIES)[number];

export type PlatformApiStatus = "documented-public-api" | "partner-gated";

export interface PlatformSpec {
  kind: PlatformKind;
  label: string;
  /** Short id prefix used in FragGate source ids. */
  idPrefix: string;
  inboundDir: string;
  /** Entities this platform's documented objects map into. */
  entities: readonly PlatformEntity[];
  /** What each vendor object becomes. Documentation for humans and tests. */
  objectMap: Readonly<Record<string, PlatformEntity>>;
  api: {
    status: PlatformApiStatus;
    /** Live pull exists in this runtime only for documented public APIs. */
    livePull: boolean;
    docsUrl: string;
    defaultBaseUrl?: string;
    auth: string;
    access: string;
  };
  writebackPermission: `${PlatformKind}.writeback`;
  honesty: string;
}

