export function isPlatformKind(value: unknown): value is PlatformKind {
  return typeof value === "string" && (PLATFORM_KINDS as readonly string[]).includes(value);
}

export function platformSpec(kind: PlatformKind): PlatformSpec {
  return PLATFORM_SPECS[kind];
}

export const PLATFORM_WRITEBACK_PERMISSIONS = PLATFORM_KINDS.map((kind) => PLATFORM_SPECS[kind].writebackPermission);
